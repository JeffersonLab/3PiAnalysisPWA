bool startsWith(const std::string &str, const std::string &prefix) {
  return str.size() >= prefix.size() && str.compare(0,prefix.size(),prefix) == 0;
}

bool endsWith(const std::string& str, const std::string& suffix) {
  //    return str.size() >= suffix.size() && str.substr(str.size() - suffix.size()) == suffix;
  return str.size() >= suffix.size() && str.compare(str.size()-suffix.size(), suffix.size(), suffix) == 0;
}




TH1F* SumInnerBySuffixPattern(TFile *file, std::string suffix) {

 std::string histname;
 std::string sumhistname = "SummedBy_" + suffix; 

 TH1F *histoSum = nullptr;

 
 TIter nextFileKey(file->GetListOfKeys());
 TKey *fileKey;


   while ((fileKey = (TKey*)nextFileKey())){

     if (!fileKey->IsFolder()) continue; //Enter a folder with any name

     TDirectory *dir = (TDirectory*)file->Get(fileKey->GetName()); 
        if (!dir) continue;
	
        TIter nextKey(dir->GetListOfKeys());
	TKey *key;

	//Inner loop over the keys in folder
	while ((key = (TKey*)nextKey())) {
     
	  if (key->GetClassName() != TString("TH1F")) continue;

	  TH1F *histo = (TH1F*)dir->Get(key->GetName());
	  histname =  histo->GetName();    

	  if (!endsWith(histname,suffix)) continue; 
	  //if (histname.find(namepattern)== std::string::npos) continue; //contains a pattern anywhere
	  //if (histname.compare(histname.size()-suffix.size(), suffix.size(), suffix) != 0) continue; //the suffix coincides with the pattern
          //cout << histo->GetName() << endl;
     
	  if (!histoSum) histoSum = (TH1F*)histo->Clone(sumhistname.c_str());
	  else  histoSum->Add(histo);      

	}
 }
 return histoSum;
}




